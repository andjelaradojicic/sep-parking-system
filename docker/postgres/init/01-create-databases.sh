#!/bin/bash
set -e
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" <<-EOSQL
  CREATE USER parking_user WITH PASSWORD '$PARKING_DB_PASSWORD';
  CREATE DATABASE parking_db OWNER parking_user;
  REVOKE CONNECT ON DATABASE parking_db FROM PUBLIC;

  CREATE USER psp_user WITH PASSWORD '$PSP_DB_PASSWORD';
  CREATE DATABASE psp_db OWNER psp_user;
  REVOKE CONNECT ON DATABASE psp_db FROM PUBLIC;

  CREATE USER bank_user WITH PASSWORD '$BANK_DB_PASSWORD';
  CREATE DATABASE bank_db OWNER bank_user;
  REVOKE CONNECT ON DATABASE bank_db FROM PUBLIC;
EOSQL
